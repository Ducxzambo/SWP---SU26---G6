package com.petclinic.backend.model;

public class Role {
    private int roleID;
    private String roleName;

    public int getRoleID() {
        return roleID;
    }

    public void setRoleID(int v) {
        roleID = v;
    }

    public String getRoleName() {
        return roleName;
    }

    public void setRoleName(String v) {
        roleName = v;
    }
}
